@router.get("/{experiment_id}/html")
def get_html_report(experiment_id: str, db: Session = Depends(get_db)):
    record = db.query(ExperimentRecord).filter(ExperimentRecord.id == experiment_id).first()
    if not record or record.status != "completed":
        raise HTTPException(400, "Experiment not completed or not found.")

    html = _build_html_report(record)
    return HTMLResponse(content=html, headers={
        "Content-Disposition": f"attachment; filename=report_{experiment_id[:8]}.html"
    })


@router.get("/{experiment_id}/json")
def get_json_report(experiment_id: str, db: Session = Depends(get_db)):
    from app.api.experiments import _serialize_experiment
    record = db.query(ExperimentRecord).filter(ExperimentRecord.id == experiment_id).first()
    if not record:
        raise HTTPException(404, "Experiment not found.")
    data = _serialize_experiment(record)
    return StreamingResponse(
        iter([json.dumps(data, indent=2)]),
        media_type="application/json",
        headers={"Content-Disposition": f"attachment; filename=experiment_{experiment_id[:8]}.json"},
    )


@router.get("/compare/csv")
def compare_experiments_csv(ids: str, db: Session = Depends(get_db)):
    """Export a comparison CSV for a comma-separated list of experiment IDs."""
    exp_ids = [i.strip() for i in ids.split(",") if i.strip()]
    records = db.query(ExperimentRecord).filter(ExperimentRecord.id.in_(exp_ids)).all()

    if not records:
        raise HTTPException(404, "No experiments found.")

    output = io.StringIO()
    writer = csv.writer(output)

    # Collect all metric keys
    all_metric_keys = set()
    for r in records:
        if r.metrics:
            all_metric_keys.update(k for k in r.metrics.keys() if k not in ("confusion_matrix", "class_names"))

    header = ["experiment_id", "model_name", "dataset_name", "task_type", "target_column",
              "n_train", "n_test", "n_features", "train_duration_s", "inference_duration_s", "status"]
    header += sorted(all_metric_keys)
    writer.writerow(header)

    for r in records:
        row = [r.id, r.model_name, r.dataset_name, r.task_type, r.target_column,
               r.n_train_rows, r.n_test_rows, r.n_features, r.train_duration_s, r.inference_duration_s, r.status]
        for k in sorted(all_metric_keys):
            row.append(r.metrics.get(k, "") if r.metrics else "")
        writer.writerow(row)

    output.seek(0)
    return StreamingResponse(
        iter([output.getvalue()]),
        media_type="text/csv",
        headers={"Content-Disposition": "attachment; filename=experiment_comparison.csv"},
    )
