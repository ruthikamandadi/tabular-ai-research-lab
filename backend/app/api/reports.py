        metrics_html += "<thead><tr><th>Metric</th><th>Value</th></tr></thead><tbody>"
        for k, v in exp.metrics.items():
            if k not in ("confusion_matrix", "class_names"):
                metrics_html += f"<tr><td>{k}</td><td>{v}</td></tr>"
        metrics_html += "</tbody></table>"

